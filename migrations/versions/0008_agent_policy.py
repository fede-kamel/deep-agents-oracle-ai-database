LOG = """
CREATE OR REPLACE PROCEDURE log_policy_event(
  p_patient IN VARCHAR2, p_run IN VARCHAR2, p_agent IN VARCHAR2, p_code IN VARCHAR2,
  p_decision IN VARCHAR2, p_detail IN VARCHAR2) AUTHID DEFINER AS
  PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
  INSERT INTO policy_event (patient_id, run_id, agent, policy_code, decision, detail)
  VALUES (p_patient, p_run, p_agent, p_code, p_decision, p_detail);
  COMMIT;
END;
"""

TRIGGER_PROPOSE = """
CREATE OR REPLACE TRIGGER trg_care_action_propose
BEFORE INSERT ON care_action FOR EACH ROW
DECLARE
  v_code     care_policy.code%TYPE;
  v_role     care_policy.required_role%TYPE;
  v_proposer care_policy.allowed_proposer%TYPE;
  v_agent    VARCHAR2(64) := NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), 'unknown');
BEGIN
  SELECT code, required_role, allowed_proposer INTO v_code, v_role, v_proposer
    FROM care_policy WHERE kind = :NEW.kind;
  IF v_proposer <> 'any' AND v_agent <> v_proposer THEN
    log_policy_event(:NEW.patient_id, :NEW.run_id, v_agent, 'CP-03', 'refused',
      v_agent || ' may not propose a ' || :NEW.kind || ' (' || :NEW.title || '); escalate to the ' || v_proposer || ' agent');
    RAISE_APPLICATION_ERROR(-20014, 'policy CP-03: the ' || v_agent || ' agent may not propose a ' || :NEW.kind
      || '; escalate it to the ' || v_proposer || ' agent with escalate_to_agent');
  END IF;
  :NEW.policy_code := v_code;
  :NEW.required_role := v_role;
  :NEW.proposed_agent := v_agent;
  :NEW.status := CASE WHEN v_role = 'physician' THEN 'needs_physician' ELSE 'proposed' END;
  :NEW.proposed_by := SYS_CONTEXT('USERENV', 'SESSION_USER');
  :NEW.created_at := SYSTIMESTAMP;
  :NEW.decided_by := NULL; :NEW.decided_at := NULL;
  :NEW.result_table := NULL; :NEW.result_id := NULL; :NEW.result_summary := NULL;
END;
"""

TRIGGER_AUDIT = """
CREATE OR REPLACE TRIGGER trg_care_action_audit
AFTER INSERT ON care_action FOR EACH ROW
BEGIN
  INSERT INTO care_action_event (action_id, patient_id, status, actor, note)
  VALUES (:NEW.id, :NEW.patient_id, 'proposed', :NEW.proposed_by || ' (' || :NEW.proposed_agent || ')',
          CASE WHEN :NEW.escalation_id IS NOT NULL
               THEN 'proposed by the ' || :NEW.proposed_agent || ' agent on escalation #' || :NEW.escalation_id
               ELSE 'drafted by the ' || :NEW.proposed_agent || ' agent' END);
  IF :NEW.status = 'needs_physician' THEN
    INSERT INTO care_action_event (action_id, patient_id, status, actor, note)
    VALUES (:NEW.id, :NEW.patient_id, 'needs_physician', 'policy ' || :NEW.policy_code,
            'policy ' || :NEW.policy_code || ': medication changes require a physician; escalated for doctor approval');
  END IF;
END;
"""

TRIGGER_ESCALATION = """
CREATE OR REPLACE TRIGGER trg_escalation_stamp
BEFORE INSERT ON agent_escalation FOR EACH ROW
BEGIN
  :NEW.from_agent := NVL(SYS_CONTEXT('USERENV', 'CLIENT_IDENTIFIER'), 'unknown');
  :NEW.status := 'open';
  :NEW.created_at := SYSTIMESTAMP;
  :NEW.resolution := NULL; :NEW.action_id := NULL; :NEW.resolved_at := NULL;
  log_policy_event(:NEW.patient_id, :NEW.run_id, :NEW.from_agent, :NEW.policy_code, 'escalated',
    'escalated to the ' || :NEW.to_agent || ' agent: ' || :NEW.subject);
END;
"""


def _policy(table: str) -> str:
    return f"""
BEGIN
  DBMS_RLS.ADD_POLICY(object_schema => 'DA_OWNER', object_name => '{table}',
    policy_name => 'DA_SCOPE_{table}', function_schema => 'DA_OWNER',
    policy_function => 'DA_PATIENT_SCOPE', statement_types => 'SELECT,INSERT,UPDATE,DELETE',
    update_check => TRUE);
END;
"""


