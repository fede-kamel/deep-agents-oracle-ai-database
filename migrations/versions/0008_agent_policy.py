"""Agent-level policy and agent-to-agent escalation.

Every care-action tool stamps its database session with the name of the agent
that called it (CLIENT_IDENTIFIER, set by tool code, not by the model). Policy
CP-03 says only the medication-safety agent may propose a medication change:
when the care coordinator tries, the proposal trigger refuses the insert
(ORA-20014), logs the refusal in policy_event through an autonomous
transaction, and tells the caller to escalate. The coordinator then writes an
agent_escalation addressed to the medication-safety agent, which reviews it
and proposes the change itself; CP-02 still sends that proposal to a doctor.

Revision ID: 0008
Revises: 0007
Create Date: 2026-10-05
"""

